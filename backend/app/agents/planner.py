MAX_SUBTASKS_PER_PLAN = 20
MAX_DEPENDENCIES_PER_SUBTASK = MAX_SUBTASKS_PER_PLAN - 1
MAX_DEPENDENCY_EDGES_PER_PLAN = MAX_SUBTASKS_PER_PLAN * MAX_DEPENDENCIES_PER_SUBTASK // 2

VALID_AGENT_ROLES: frozenset[str] = frozenset(
    {"research", "coding", "document", "email", "pm", "browser", "file"}
)


class PlannerError(Exception):
    """Base error for planning and decomposition failures."""


class PlanCycleError(PlannerError):
    """Raised when circular dependencies are detected in the subtask graph."""


class MaxSubtasksExceededError(PlannerError):
    """Raised when a plan exceeds the maximum allowed subtask count."""


class PlanValidationError(PlannerError):
    """Raised when a plan violates structural constraints (missing nodes, empty plan, etc.)."""


class MaxDependencyEdgesExceededError(PlanValidationError):
    """Raised when a plan exceeds the maximum number of distinct dependency edges."""


class SubTaskPlanItem(BaseModel):
    """Structured subtask item generated by the model during decomposition."""

    id: str
    # A plain string with an enum in the published schema: an unexpected role is repaired to
    # ``executor`` by ``repair_plan`` instead of failing the whole model response.
    assigned_agent: str = Field(json_schema_extra={"enum": list(PLANNER_FACING_ROLES)})
    description: str
    dependencies: list[str] = Field(
        default_factory=list,
        max_length=MAX_DEPENDENCIES_PER_SUBTASK,
        json_schema_extra={"uniqueItems": True},
    )
    input_data: dict[str, Any] = Field(default_factory=dict)
    requires_approval: bool = False
    tool: str | None = None
    tool_args: dict[str, Any] = Field(default_factory=dict)
    # False = the task may finish without this step's output (it is reported as a warning).
    critical: bool | None = None

    @field_validator("dependencies")
    @classmethod
    def dependencies_are_unique(cls, dependencies: list[str]) -> list[str]:
        if len(dependencies) != len(set(dependencies)):
            raise ValueError("Dependencies must not contain repeated edges")
        return dependencies


class PlanDecompositionResponse(BaseModel):
    """Schema for model-generated decomposition."""

    intent: str
    subtasks: list[SubTaskPlanItem] = Field(
        default_factory=list,
        max_length=MAX_SUBTASKS_PER_PLAN,
    )
    # True (with an empty ``subtasks``) when the request needs the user's private data or an
    # integration that is not connected: the task is then refused instead of planned.
    unsupported: bool = False
    unsupported_reason: str = ""
    unsupported_hint: str = ""
    # Set (with an empty ``subtasks``) when a deliverable is requested but no subject was given.
    needs_clarification: bool = False
    clarification_question: str = ""

    @model_validator(mode="after")
    def needs_steps_unless_unsupported(self) -> PlanDecompositionResponse:
        if not self.unsupported and not self.needs_clarification and not self.subtasks:
            raise ValueError("A plan needs at least one subtask")
        return self


def build_dependency_graph(subtasks: Sequence[SubTask]) -> dict[str, set[str]]:
    """Build a map from subtask id to its set of dependency ids."""
    topological_sort(subtasks)
    return {st.id: set(st.dependencies) for st in subtasks}


def topological_sort(subtasks: Sequence[SubTask]) -> list[SubTask]:
    """Sort subtasks in topological order using Kahn's algorithm.

    Raises:
        PlanValidationError: If graph entries or dependencies are malformed, or the edge bound
            is exceeded.
        PlanCycleError: If the graph contains a cycle.
    """
    if not isinstance(subtasks, Sequence) or isinstance(subtasks, (str, bytes, bytearray)):
        raise PlanValidationError("Expected a sequence of SubTask instances")
    if not subtasks:
        return []

    task_map: dict[str, SubTask] = {}
    for st in subtasks:
        if not isinstance(st, SubTask):
            raise PlanValidationError("Each graph entry must be a SubTask")
        if not isinstance(st.id, str):
            raise PlanValidationError("Subtask id must be a string")
        if not isinstance(st.dependencies, list) or not all(
            isinstance(dep, str) for dep in st.dependencies
        ):
            raise PlanValidationError(f"Subtask '{st.id}' dependencies must be a list of strings")
        if st.id in task_map:
            raise PlanValidationError(f"Duplicate subtask id detected: '{st.id}'")
        task_map[st.id] = st

    edge_count = 0
    for st in subtasks:
        if len(st.dependencies) != len(set(st.dependencies)):
            raise PlanValidationError(f"Subtask '{st.id}' has repeated dependency edges")
        for dep in st.dependencies:
            if dep not in task_map:
                raise PlanValidationError(
                    f"Subtask '{st.id}' depends on non-existent subtask '{dep}'"
                )
        edge_count += len(st.dependencies)

    if edge_count > MAX_DEPENDENCY_EDGES_PER_PLAN:
        raise MaxDependencyEdgesExceededError(
            f"Plan has {edge_count} dependency edges; exceeds dependency edge limit of "
            f"{MAX_DEPENDENCY_EDGES_PER_PLAN}"
        )

    in_degree: dict[str, int] = {st.id: len(st.dependencies) for st in subtasks}
    dependents: dict[str, list[str]] = {st.id: [] for st in subtasks}

    for st in subtasks:
        for dep in st.dependencies:
            if dep in dependents:
                dependents[dep].append(st.id)

    # Queue of nodes with zero in-degree (no unresolved dependencies)
    queue: deque[str] = deque([st.id for st in subtasks if in_degree[st.id] == 0])
    sorted_tasks: list[SubTask] = []

    while queue:
        current_id = queue.popleft()
        sorted_tasks.append(task_map[current_id])

        for dependent_id in dependents.get(current_id, []):
            in_degree[dependent_id] -= 1
            if in_degree[dependent_id] == 0:
                queue.append(dependent_id)

    if len(sorted_tasks) != len(subtasks):
        unresolved = [st.id for st in subtasks if in_degree[st.id] > 0]
        raise PlanCycleError(
            f"Circular dependency detected in plan graph involving tasks: {sorted(unresolved)}"
        )

    return sorted_tasks


def validate_dag(subtasks: Sequence[SubTask]) -> list[SubTask]:
    """Validate graph constraints and return the subtasks in topological execution order.

    Constraints:
        1. Subtasks list cannot be empty.
        2. Maximum 20 subtasks allowed.
        3. No duplicate subtask IDs.
        4. Every dependency ID must exist within the plan and be unique per subtask.
        5. No more than 190 dependency edges across the plan.
        6. No self-dependencies.
        7. Graph must be an acyclic DAG.
    """
    if not subtasks:
        raise PlanValidationError("Plan must contain at least one subtask")

    if len(subtasks) > MAX_SUBTASKS_PER_PLAN:
        raise MaxSubtasksExceededError(
            f"Plan has {len(subtasks)} subtasks; exceeds maximum limit of {MAX_SUBTASKS_PER_PLAN}"
        )

    seen_ids: set[str] = set()
    for st in subtasks:
        if st.id in seen_ids:
            raise PlanValidationError(f"Duplicate subtask id detected: '{st.id}'")
        seen_ids.add(st.id)

    for st in subtasks:
        if st.assigned_agent not in VALID_AGENT_ROLES:
            raise PlanValidationError(
                f"Subtask '{st.id}' assigned unknown agent role '{st.assigned_agent}'"
            )

    return topological_sort(subtasks)


