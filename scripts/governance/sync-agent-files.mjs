// Generates the thin per-tool agent wrappers from the canonical sources and verifies
// that hand-written entry points still reference AGENTS.md.
//
// Canonical sources:  AGENTS.md (hard-rules block), governance/workflows/*.md, governance/roles/*.md
// Generated outputs:  .claude/skills/gov-*  .claude/agents/role-*  .agents/skills/gov-*
//                     .github/prompts/gov-*  .cursor/rules/gov-*  .cursor/rules/maya-governance.mdc
//                     .github/copilot-instructions.md
//
// Usage: node scripts/governance/sync-agent-files.mjs [--check] [--root <dir>]
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, EXIT, walk, exists, readText, writeText, normalizeEol, isMain, argValue } from '../lib/fsutil.mjs';
import { loadConfig } from '../lib/config.mjs';
import { parseFrontmatter } from '../lib/frontmatter.mjs';
import { matchGlob } from '../lib/glob.mjs';

const GEN = (src) =>
  `<!-- GENERATED by scripts/governance/sync-agent-files.mjs from ${src}. Do not edit by hand; run "npm run agents:sync". -->`;
const q = (s) => JSON.stringify(s);

function loadSources(root) {
  const problems = [];
  const read = (dir, kind) =>
    walk(root, dir)
      .filter((f) => f.endsWith('.md') && !f.endsWith('/README.md'))
      .map((file) => {
        const { data } = parseFrontmatter(readText(root, file));
        const id = path.posix.basename(file, '.md');
        if (data.name !== id) problems.push(`${file}: front matter name "${data.name}" must equal the file name "${id}"`);
        if (!data.description) problems.push(`${file}: front matter description is required`);
        return { id, file, kind, description: data.description ?? '', claudeTools: data.claude_tools ?? null };
      });
  return { workflows: read('governance/workflows', 'workflow'), roles: read('governance/roles', 'role'), problems };
}

export function extractHardRules(agentsText, markers) {
  const [begin, end] = markers;
  const text = normalizeEol(agentsText);
  const a = text.indexOf(begin);
  const b = text.indexOf(end);
  if (a === -1 || b === -1 || b < a) return null;
  return text.slice(a + begin.length, b).trim();
}

/** Compute every generated file. Returns { files: Map(path -> content), problems: string[] }. */
export function buildExpected(root) {
  const cfg = loadConfig(root);
  const { prefix, rolePrefix, hardRulesMarkers } = cfg.agentWrappers;
  const { workflows, roles, problems } = loadSources(root);
  const files = new Map();

  for (const w of workflows) {
    const name = `${prefix}${w.id}`;
    const pointer =
      `Read \`${w.file}\` and follow it step by step, together with \`AGENTS.md\`. ` +
      'The workflow file is the source of truth; this file only points to it.';

    files.set(
      `.claude/skills/${name}/SKILL.md`,
      `---\nname: ${name}\ndescription: ${q(w.description)}\nargument-hint: "[task or reference]"\ndisable-model-invocation: true\n---\n${GEN(w.file)}\n\n${pointer}\n\nTask input: $ARGUMENTS\n`,
    );
    files.set(
      `.agents/skills/${name}/SKILL.md`,
      `---\nname: ${name}\ndescription: ${q(w.description)}\n---\n${GEN(w.file)}\n\n${pointer}\n\nThe user's request follows the invocation of this skill.\n`,
    );
    files.set(
      `.github/prompts/${name}.prompt.md`,
      `---\nname: ${q(name)}\ndescription: ${q(w.description)}\nagent: agent\n---\n${GEN(w.file)}\n\n${pointer}\n`,
    );
    files.set(
      `.cursor/rules/${name}.mdc`,
      `---\ndescription: ${q(w.description)}\nalwaysApply: false\n---\n${GEN(w.file)}\n\n${pointer}\n`,
    );
  }

  for (const r of roles) {
    const name = `${rolePrefix}${r.id}`;
    const tools = r.claudeTools ? `tools: ${r.claudeTools}\n` : '';
    files.set(
      `.claude/agents/${name}.md`,
      `---\nname: ${name}\ndescription: ${q(r.description)}\n${tools}---\n${GEN(r.file)}\n\n` +
        `You are acting in the role defined in \`${r.file}\`. Read that file and \`AGENTS.md\` first and follow them. ` +
        'Role assignment grants no additional permissions: the permission levels in `governance/TOOL_PERMISSIONS.md` still apply, ' +
        'and Level 3 actions need explicit human approval.\n',
    );
  }

  const agentsPath = 'AGENTS.md';
  if (!exists(root, agentsPath)) {
    problems.push('AGENTS.md is missing');
  } else {
    const rules = extractHardRules(readText(root, agentsPath), hardRulesMarkers);
    if (!rules) {
      problems.push(`AGENTS.md must contain the hard-rules block between ${hardRulesMarkers.join(' and ')}`);
    } else {
      const intro =
        'The canonical instructions for every AI agent in this repository are in `AGENTS.md`; read it first. ' +
        'Detailed policy is in `governance/README.md`, reusable workflows in `governance/workflows/`, and role definitions in `governance/roles/`. ' +
        'There is no application code yet; do not implement product features unless asked.';
      files.set(
        '.github/copilot-instructions.md',
        `${GEN(agentsPath)}\n\n# Copilot instructions: MAYA AI (MYAI)\n\n${intro}\n\n${rules}\n`,
      );
      files.set(
        '.cursor/rules/maya-governance.mdc',
        `---\ndescription: MAYA AI governance hard rules (mirrors AGENTS.md)\nalwaysApply: true\n---\n${GEN(agentsPath)}\n\n${intro}\n\n${rules}\n`,
      );
    }
  }
  return { files, problems };
}

/** Existing files this generator owns (by name prefix), used to find stale outputs. */
export function ownedFiles(root, cfg) {
  const { prefix, rolePrefix } = cfg.agentWrappers;
  const owned = [
    { dir: '.claude/skills', glob: `.claude/skills/${prefix}*/**` },
    { dir: '.agents/skills', glob: `.agents/skills/${prefix}*/**` },
    { dir: '.github/prompts', glob: `.github/prompts/${prefix}*` },
    { dir: '.cursor/rules', glob: `.cursor/rules/${prefix}*` },
    { dir: '.claude/agents', glob: `.claude/agents/${rolePrefix}*` },
  ];
  const out = [];
  for (const { dir, glob } of owned) {
    if (!exists(root, dir)) continue;
    for (const f of walk(root, dir)) if (matchGlob(f, glob)) out.push(f);
  }
  return out;
}

function checkEntryPoints(root, cfg) {
  const errors = [];
  const hasLine = (file, line) =>
    exists(root, file) && normalizeEol(readText(root, file)).split('\n').some((l) => l.trim() === line);

  if (!hasLine('CLAUDE.md', '@AGENTS.md')) errors.push('CLAUDE.md must import the canonical file with a line "@AGENTS.md"');
  if (!hasLine('GEMINI.md', '@./AGENTS.md')) errors.push('GEMINI.md must import the canonical file with a line "@./AGENTS.md"');

  const instructionsDir = '.github/instructions';
  if (exists(root, instructionsDir)) {
    for (const f of walk(root, instructionsDir)) {
      if (f.endsWith('.instructions.md') && !readText(root, f).includes('AGENTS.md')) {
        errors.push(`${f} must reference AGENTS.md`);
      }
    }
  }

  if (exists(root, '.claude/settings.json')) {
    try {
      const s = JSON.parse(readText(root, '.claude/settings.json'));
      if (!Array.isArray(s?.permissions?.deny) || s.permissions.deny.length === 0) {
        errors.push('.claude/settings.json must define permissions.deny rules');
      }
      if (!Array.isArray(s?.permissions?.ask) || s.permissions.ask.length === 0) {
        errors.push('.claude/settings.json must define permissions.ask rules');
      }
    } catch (e) {
      errors.push(`.claude/settings.json is not valid JSON (${e.message})`);
    }
  }

  const limits = cfg.instructionFiles;
  for (const f of limits.files) {
    if (!exists(root, f)) continue;
    const bytes = Buffer.byteLength(readText(root, f), 'utf8');
    if (bytes > limits.maxBytes) errors.push(`${f} is ${bytes} bytes; the limit is ${limits.maxBytes} (Antigravity truncates above it)`);
  }
  return errors;
}

export function checkAgentFiles(root = ROOT) {
  const cfg = loadConfig(root);
  const { files, problems } = buildExpected(root);
  const errors = [...problems];

  for (const [rel, content] of files) {
    if (!exists(root, rel)) errors.push(`${rel}: missing (run "npm run agents:sync")`);
    else if (normalizeEol(readText(root, rel)) !== content) errors.push(`${rel}: out of date (run "npm run agents:sync")`);
  }
  for (const rel of ownedFiles(root, cfg)) {
    if (!files.has(rel)) errors.push(`${rel}: stale generated file with no canonical source (run "npm run agents:sync")`);
  }
  errors.push(...checkEntryPoints(root, cfg));
  return { errors, expected: files.size };
}

function sync(root) {
  const cfg = loadConfig(root);
  const { files, problems } = buildExpected(root);
  if (problems.length > 0) return { problems, written: 0, removed: 0, unchanged: 0 };

  let written = 0;
  let unchanged = 0;
  for (const [rel, content] of files) {
    if (exists(root, rel) && normalizeEol(readText(root, rel)) === content) {
      unchanged += 1;
    } else {
      writeText(root, rel, content);
      written += 1;
    }
  }
  let removed = 0;
  for (const rel of ownedFiles(root, cfg)) {
    if (files.has(rel)) continue;
    fs.rmSync(path.join(root, rel));
    removed += 1;
    const dir = path.dirname(path.join(root, rel));
    if (fs.existsSync(dir) && fs.readdirSync(dir).length === 0) fs.rmdirSync(dir);
  }
  return { problems: [], written, removed, unchanged };
}

function main() {
  const argv = process.argv.slice(2);
  const root = argValue(argv, '--root') ?? ROOT;

  if (argv.includes('--check')) {
    const r = checkAgentFiles(root);
    if (r.errors.length === 0) {
      console.log(`agent files: ${r.expected} generated files match their sources and all entry points reference AGENTS.md.`);
      process.exit(EXIT.PASS);
    }
    console.error(`agent files: ${r.errors.length} problem(s):`);
    for (const e of r.errors) console.error(`  ${e}`);
    process.exit(EXIT.FAIL);
  }

  const r = sync(root);
  if (r.problems.length > 0) {
    console.error('Cannot generate agent files:');
    for (const p of r.problems) console.error(`  ${p}`);
    process.exit(EXIT.FAIL);
  }
  console.log(`agent files: ${r.written} written, ${r.unchanged} unchanged, ${r.removed} removed.`);
  const entry = checkEntryPoints(root, loadConfig(root));
  if (entry.length > 0) {
    console.error('Entry-point problems:');
    for (const e of entry) console.error(`  ${e}`);
    process.exit(EXIT.FAIL);
  }
}

if (isMain(import.meta.url)) main();
